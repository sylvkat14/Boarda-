CREATE TABLE IF NOT EXISTS listing_amenities (
  listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  amenity_id BIGINT NOT NULL REFERENCES amenities(id) ON DELETE CASCADE,
  PRIMARY KEY (listing_id, amenity_id)
);

CREATE INDEX IF NOT EXISTS listing_amenities_amenity_id_idx
  ON listing_amenities(amenity_id);

CREATE TABLE IF NOT EXISTS saved_listings (
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (student_user_id, listing_id)
);

CREATE INDEX IF NOT EXISTS saved_listings_listing_id_idx
  ON saved_listings(listing_id);

CREATE TABLE IF NOT EXISTS listing_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT NOT NULL CHECK (LENGTH(TRIM(message)) > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'new'
    CHECK (status IN ('new', 'read', 'replied', 'closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS listing_inquiries_listing_created_idx
  ON listing_inquiries(listing_id, created_at DESC);
CREATE INDEX IF NOT EXISTS listing_inquiries_student_created_idx
  ON listing_inquiries(student_user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS inquiry_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id BIGINT NOT NULL REFERENCES listing_inquiries(id) ON DELETE CASCADE,
  sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT NOT NULL CHECK (LENGTH(TRIM(message)) BETWEEN 1 AND 4000),
  is_initial BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS inquiry_messages_one_initial_idx
  ON inquiry_messages(inquiry_id) WHERE is_initial;
CREATE INDEX IF NOT EXISTS inquiry_messages_inquiry_id_idx
  ON inquiry_messages(inquiry_id, id);

INSERT INTO inquiry_messages (inquiry_id, sender_user_id, message, is_initial, created_at)
SELECT id, student_user_id, message, TRUE, created_at
FROM listing_inquiries
ORDER BY created_at, id
ON CONFLICT (inquiry_id) WHERE is_initial DO NOTHING;

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(40) NOT NULL,
  title VARCHAR(150) NOT NULL,
  message TEXT NOT NULL,
  target_url VARCHAR(500),
  source_type VARCHAR(40),
  source_id BIGINT,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, source_type, source_id)
);

CREATE INDEX IF NOT EXISTS notifications_user_created_idx
  ON notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notifications_unread_idx
  ON notifications(user_id, created_at DESC)
  WHERE read_at IS NULL;

INSERT INTO notifications (
  user_id, type, title, message, target_url, source_type, source_id, read_at, created_at
)
SELECT
  listing.owner_user_id,
  'student_inquiry',
  'New student inquiry',
  student.name || ' sent an inquiry about ' || listing.title || '.',
  '/Frontend/landlord-dashboard.html',
  'listing_inquiry_landlord',
  inquiry.id,
  CASE WHEN inquiry.status = 'new' THEN NULL ELSE inquiry.created_at END,
  inquiry.created_at
FROM listing_inquiries AS inquiry
JOIN listings AS listing ON listing.id = inquiry.listing_id
JOIN users AS student ON student.id = inquiry.student_user_id
WHERE listing.owner_user_id IS NOT NULL
ON CONFLICT (user_id, source_type, source_id) DO NOTHING;

